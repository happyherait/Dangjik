-- 당직(Dangjik) 기본 스키마. 모든 데이터는 가상이다.

-- 직원과 입점사 사용자
CREATE TABLE partners (
  partner_id      VARCHAR2(20)  PRIMARY KEY,
  name            VARCHAR2(100 CHAR) NOT NULL,
  status          VARCHAR2(20)  NOT NULL,
  commission_rate NUMBER(5,2)   NOT NULL
);

CREATE TABLE staff_users (
  user_id    VARCHAR2(30)  PRIMARY KEY,
  name       VARCHAR2(50 CHAR) NOT NULL,
  role       VARCHAR2(20)  NOT NULL
             CHECK (role IN ('CS_AGENT', 'OPS_ENGINEER', 'OPS_LEAD', 'MARKETER', 'PARTNER')),
  partner_id VARCHAR2(20)  REFERENCES partners(partner_id)
);

-- 몰
CREATE TABLE members (
  member_id VARCHAR2(20)  PRIMARY KEY,
  name      VARCHAR2(50 CHAR) NOT NULL,
  email     VARCHAR2(100) NOT NULL,
  grade     VARCHAR2(20)  NOT NULL,
  joined_at DATE          NOT NULL
);

CREATE TABLE products (
  product_id  VARCHAR2(20)  PRIMARY KEY,
  partner_id  VARCHAR2(20)  NOT NULL REFERENCES partners(partner_id),
  name        VARCHAR2(200 CHAR) NOT NULL,
  category    VARCHAR2(50 CHAR)  NOT NULL,
  price       NUMBER(12)    NOT NULL CHECK (price >= 0),
  stock       NUMBER(9)     NOT NULL CHECK (stock >= 0),
  description VARCHAR2(2000 CHAR),
  status      VARCHAR2(20)  NOT NULL
);

CREATE TABLE orders (
  order_id     VARCHAR2(30) PRIMARY KEY,
  member_id    VARCHAR2(20) NOT NULL REFERENCES members(member_id),
  channel      VARCHAR2(10) NOT NULL CHECK (channel IN ('WEB', 'APP')),
  status       VARCHAR2(20) NOT NULL
               CHECK (status IN ('PAYMENT_PENDING', 'PAID', 'SHIPPING', 'DELIVERED', 'CANCELED')),
  total_amount NUMBER(12)   NOT NULL,
  ordered_at   TIMESTAMP    NOT NULL
);

CREATE TABLE order_items (
  order_id        VARCHAR2(30) NOT NULL REFERENCES orders(order_id),
  line_no         NUMBER(3)    NOT NULL,
  product_id      VARCHAR2(20) NOT NULL REFERENCES products(product_id),
  qty             NUMBER(5)    NOT NULL CHECK (qty > 0),
  unit_price      NUMBER(12)   NOT NULL,
  shipment_status VARCHAR2(20) NOT NULL,
  PRIMARY KEY (order_id, line_no)
);

-- 우리 쪽 결제 기록. 주문당 하나
CREATE TABLE payments (
  payment_id VARCHAR2(30) PRIMARY KEY,
  order_id   VARCHAR2(30) NOT NULL UNIQUE REFERENCES orders(order_id),
  pg_tx_id   VARCHAR2(40) NOT NULL UNIQUE,
  amount     NUMBER(12)   NOT NULL,
  paid_at    TIMESTAMP    NOT NULL
);

-- 가상 PG사 원장. PG가 알고 있는 사실이며 우리 DB와 어긋날 수 있다
CREATE TABLE pg_transactions (
  pg_tx_id    VARCHAR2(40) PRIMARY KEY,
  order_id    VARCHAR2(30) NOT NULL,
  status      VARCHAR2(20) NOT NULL CHECK (status IN ('APPROVED', 'CANCELED', 'FAILED')),
  amount      NUMBER(12)   NOT NULL,
  approved_at TIMESTAMP
);

-- PG 결제 알림(웹훅) 수신 기록
CREATE TABLE webhook_logs (
  log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pg_tx_id    VARCHAR2(40) NOT NULL,
  order_id    VARCHAR2(30) NOT NULL,
  http_status NUMBER(3)    NOT NULL,
  message     VARCHAR2(500 CHAR),
  received_at TIMESTAMP    NOT NULL
);

-- 파트너 포털
CREATE TABLE claims (
  claim_id     VARCHAR2(30) PRIMARY KEY,
  order_id     VARCHAR2(30) NOT NULL REFERENCES orders(order_id),
  claim_type   VARCHAR2(20) NOT NULL CHECK (claim_type IN ('CANCEL', 'RETURN', 'EXCHANGE')),
  status       VARCHAR2(20) NOT NULL,
  reason       VARCHAR2(500 CHAR),
  requested_at TIMESTAMP    NOT NULL
);

CREATE TABLE settlements (
  settlement_id VARCHAR2(30) PRIMARY KEY,
  partner_id    VARCHAR2(20) NOT NULL REFERENCES partners(partner_id),
  period        VARCHAR2(7)  NOT NULL,
  gross_amount  NUMBER(14)   NOT NULL,
  commission    NUMBER(14)   NOT NULL,
  net_amount    NUMBER(14)   NOT NULL,
  status        VARCHAR2(20) NOT NULL,
  CONSTRAINT uq_settlement UNIQUE (partner_id, period)
);

-- CRM
CREATE TABLE coupons (
  coupon_id     VARCHAR2(20) PRIMARY KEY,
  name          VARCHAR2(100 CHAR) NOT NULL,
  discount_rate NUMBER(3)    NOT NULL CHECK (discount_rate BETWEEN 1 AND 90),
  valid_to      DATE         NOT NULL,
  status        VARCHAR2(20) NOT NULL
);

CREATE TABLE cs_inquiries (
  inquiry_id VARCHAR2(30) PRIMARY KEY,
  member_id  VARCHAR2(20) NOT NULL REFERENCES members(member_id),
  order_id   VARCHAR2(30) REFERENCES orders(order_id),
  channel    VARCHAR2(20) NOT NULL,
  title      VARCHAR2(200 CHAR) NOT NULL,
  body       VARCHAR2(2000 CHAR) NOT NULL,
  status     VARCHAR2(20) NOT NULL,
  created_at TIMESTAMP    NOT NULL
);

-- 모바일 앱
CREATE TABLE app_versions (
  platform              VARCHAR2(10) PRIMARY KEY CHECK (platform IN ('ANDROID', 'IOS')),
  latest_version        VARCHAR2(20) NOT NULL,
  min_supported_version VARCHAR2(20) NOT NULL,
  updated_at            TIMESTAMP    NOT NULL
);

-- 운영 콘솔
CREATE TABLE sr_tickets (
  ticket_id   VARCHAR2(30) PRIMARY KEY,
  area        VARCHAR2(10) NOT NULL CHECK (area IN ('MALL', 'PARTNER', 'CRM', 'APP')),
  severity    VARCHAR2(10) NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
  title       VARCHAR2(200 CHAR) NOT NULL,
  description VARCHAR2(2000 CHAR),
  status      VARCHAR2(20) NOT NULL,
  inquiry_id  VARCHAR2(30) REFERENCES cs_inquiries(inquiry_id),
  created_by  VARCHAR2(30) NOT NULL REFERENCES staff_users(user_id),
  created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE deployments (
  deploy_id   VARCHAR2(30) PRIMARY KEY,
  area        VARCHAR2(20) NOT NULL,
  version     VARCHAR2(20) NOT NULL,
  note        VARCHAR2(500 CHAR),
  deployed_by VARCHAR2(30) NOT NULL REFERENCES staff_users(user_id),
  deployed_at TIMESTAMP    NOT NULL
);

CREATE TABLE batch_jobs (
  job_id       VARCHAR2(30) PRIMARY KEY,
  name         VARCHAR2(100 CHAR) NOT NULL,
  last_status  VARCHAR2(20) NOT NULL,
  last_message VARCHAR2(500 CHAR),
  last_run_at  TIMESTAMP
);

-- 런북 실행 요청. 같은 멱등키로는 한 번만 실행된다
CREATE TABLE runbook_runs (
  run_id          VARCHAR2(30)  PRIMARY KEY,
  runbook_id      VARCHAR2(40)  NOT NULL,
  ticket_id       VARCHAR2(30)  REFERENCES sr_tickets(ticket_id),
  requested_by    VARCHAR2(30)  NOT NULL REFERENCES staff_users(user_id),
  plan_hash       VARCHAR2(64)  NOT NULL,
  plan_json       CLOB          NOT NULL,
  status          VARCHAR2(20)  NOT NULL
                  CHECK (status IN ('WAITING_APPROVAL', 'REJECTED', 'EXECUTED', 'FAILED')),
  idempotency_key VARCHAR2(64)  NOT NULL UNIQUE,
  created_at      TIMESTAMP     NOT NULL,
  executed_at     TIMESTAMP
);

CREATE TABLE approvals (
  approval_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id      VARCHAR2(30) NOT NULL REFERENCES runbook_runs(run_id),
  approver_id VARCHAR2(30) NOT NULL REFERENCES staff_users(user_id),
  decision    VARCHAR2(10) NOT NULL CHECK (decision IN ('APPROVE', 'REJECT')),
  plan_hash   VARCHAR2(64) NOT NULL,
  reason      VARCHAR2(500 CHAR),
  decided_at  TIMESTAMP    NOT NULL
);

CREATE TABLE audit_events (
  event_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id   VARCHAR2(30)  NOT NULL,
  action     VARCHAR2(50)  NOT NULL,
  target     VARCHAR2(100) NOT NULL,
  detail     VARCHAR2(4000 CHAR),
  created_at TIMESTAMP     NOT NULL
);
